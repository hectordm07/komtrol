create table if not exists public.materials (
  id uuid primary key default gen_random_uuid(),
  material_no text not null,
  stock_code text,
  description text not null,
  location text,
  warehouse text,
  price numeric(16,2),
  notes text,
  status text not null default 'ACTIVO'
    check (status in ('ACTIVO','INACTIVO','OBSERVADO')),
  updated_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (material_no, warehouse)
);
alter table public.materials enable row level security;

create index if not exists materials_material_idx on public.materials(material_no);
create index if not exists materials_stock_code_idx on public.materials(stock_code);
create index if not exists materials_warehouse_idx on public.materials(warehouse);
create index if not exists materials_location_idx on public.materials(location);

