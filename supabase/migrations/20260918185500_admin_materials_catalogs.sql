create table if not exists public.material_history (
  id bigint generated by default as identity primary key,
  material_id uuid not null references public.materials(id) on delete cascade,
  action text not null,
  old_values jsonb,
  new_values jsonb,
  changed_by uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);
alter table public.material_history enable row level security;
create index if not exists material_history_material_idx on public.material_history(material_id);

drop policy if exists "material_history_admin_select" on public.material_history;
create policy "material_history_admin_select"
on public.material_history for select
to authenticated
using ((select private.current_user_komtrol_role()) = 'ADMINISTRADOR');

drop policy if exists "material_history_admin_insert" on public.material_history;
create policy "material_history_admin_insert"
on public.material_history for insert
to authenticated
with check ((select private.current_user_komtrol_role()) = 'ADMINISTRADOR' and changed_by = (select auth.uid()));

create table if not exists public.bulk_imports (
