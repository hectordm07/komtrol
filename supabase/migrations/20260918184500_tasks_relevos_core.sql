drop policy if exists "task_history_select_scope" on public.task_history;
create policy "task_history_select_scope"
on public.task_history for select
to authenticated
using (
  exists (
    select 1 from public.tasks t
    where t.id = task_id
      and (
        t.created_by = (select auth.uid())
        or t.responsible_id = (select auth.uid())
        or (select private.current_user_komtrol_role()) in ('SUPERVISOR','ADMINISTRADOR')
        or (
          (select private.current_user_komtrol_role()) = 'COORDINADOR'
          and t.warehouse is not distinct from (select private.current_user_warehouse())
        )
      )
  )
);

drop policy if exists "task_history_insert_authenticated" on public.task_history;
create policy "task_history_insert_authenticated"
on public.task_history for insert
to authenticated
with check (changed_by = (select auth.uid()));

