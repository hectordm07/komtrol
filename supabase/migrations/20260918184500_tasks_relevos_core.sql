create or replace function private.current_user_warehouse()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select up.warehouse
  from public.user_profiles up
  where up.user_id = auth.uid() and up.active = true
  limit 1
$$;

revoke all on function private.current_user_warehouse() from public;
grant usage on schema private to authenticated;
grant execute on function private.current_user_warehouse() to authenticated;

drop policy if exists "profiles_select_own_or_manager" on public.user_profiles;
create policy "profiles_select_own_or_manager"
on public.user_profiles for select
to authenticated
using (
  (select auth.uid()) = user_id
  or (select private.current_user_komtrol_role()) in ('SUPERVISOR','ADMINISTRADOR')
  or (
    (select private.current_user_komtrol_role()) = 'COORDINADOR'
    and warehouse is not distinct from (select private.current_user_warehouse())
  )
);

create table if not exists public.tasks (
  id uuid primary key default gen_random_uuid(),
  task_no text not null unique,
  work_type text not null default 'TAREA'
    check (work_type in ('TAREA','RELEVO','PERSONAL')),
  title text not null,
  description text,
  warehouse text,
  project text,
  group_name text,
  responsible_id uuid references auth.users(id),
  created_by uuid not null references auth.users(id),
  category text,
  tags text[] not null default '{}',
  priority text not null default 'MEDIA'
    check (priority in ('BAJA','MEDIA','ALTA','URGENTE')),
  status text not null default 'PENDIENTE'
    check (status in ('PENDIENTE','EN_PROCESO','BLOQUEADO','CERRADO','VENCIDA')),
  progress smallint not null default 0 check (progress between 0 and 100),
  start_at timestamptz,
  due_at timestamptz,
  closed_at timestamptz,
  estimated_hours numeric(10,2),
  email_subject text,
  email_related boolean not null default false,
  extensions_count integer not null default 0,
  original_due_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.tasks enable row level security;

create index if not exists tasks_created_by_idx on public.tasks(created_by);
create index if not exists tasks_responsible_idx on public.tasks(responsible_id);
create index if not exists tasks_warehouse_idx on public.tasks(warehouse);
create index if not exists tasks_due_at_idx on public.tasks(due_at);
create index if not exists tasks_status_idx on public.tasks(status);
create index if not exists tasks_work_type_idx on public.tasks(work_type);

drop policy if exists "tasks_select_scope" on public.tasks;
create policy "tasks_select_scope"
on public.tasks for select
to authenticated
using (
  created_by = (select auth.uid())
  or responsible_id = (select auth.uid())
  or (select private.current_user_komtrol_role()) in ('SUPERVISOR','ADMINISTRADOR')
  or (
    (select private.current_user_komtrol_role()) = 'COORDINADOR'
    and warehouse is not distinct from (select private.current_user_warehouse())
  )
);

drop policy if exists "tasks_insert_authenticated" on public.tasks;
create policy "tasks_insert_authenticated"
on public.tasks for insert
to authenticated
with check (
  created_by = (select auth.uid())
  and exists (
    select 1 from public.user_profiles p
    where p.user_id = (select auth.uid()) and p.active = true
  )
);

